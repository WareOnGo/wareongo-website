import fs from 'node:fs/promises';
import path from 'node:path';
import { fetchLocations, fetchMicromarkets } from './lib/api.mjs';
import { popularLocationIds } from './lib/navigation-popularity.mjs';
import {
  fetchAllWarehouses,
  summarize,
  locationTypeCombos,
  summarizeMicromarkets,
  filterMicromarkets,
  CITY_MIN_LISTINGS,
} from './lib/locations.mjs';

// Pivot the combo list into { PEB: LocationSummary[]; RCC: LocationSummary[] }
// for use by the footer link sections.
function groupByType(combos) {
  const out = { PEB: [], RCC: [] };
  for (const c of combos) {
    out[c.warehouseType].push({
      canonical: c.location.canonical,
      slug: c.location.slug,
      count: c.count,
    });
  }
  for (const key of Object.keys(out)) {
    out[key].sort((a, b) => a.canonical.localeCompare(b.canonical));
  }
  return out;
}

async function main() {
  const [warehouses, aggregates, allMicromarkets] = await Promise.all([
    fetchAllWarehouses(), fetchLocations(), fetchMicromarkets(),
  ]);
  const cities = summarize(warehouses, 'city');
  const states = summarize(warehouses, 'state');
  const micromarkets = await summarizeMicromarkets(allMicromarkets);
  const filterMarkets = filterMicromarkets(warehouses, allMicromarkets);
  const cityByType = groupByType(locationTypeCombos(warehouses, 'city'));
  const stateByType = groupByType(locationTypeCombos(warehouses, 'state'));
  const popular = popularLocationIds({ cities, states, micromarkets }, aggregates, CITY_MIN_LISTINGS);

  const body = `// AUTO-GENERATED by scripts/generate-locations.mjs — do not edit by hand.
// Regenerated on every \`npm run build\`. Sources: backend warehouses, locations and micromarkets APIs.

export interface LocationSummary {
  canonical: string;
  slug: string;
  count: number;
}

export interface LocationsByType {
  PEB: LocationSummary[];
  RCC: LocationSummary[];
}

export interface MicromarketSummary extends LocationSummary {
  parentCity: string;
  /** The {city} in /listings/city/{city}/{slug}. */
  citySlug: string;
}

// Listings a city needs before its page is advertised in the footer or the
// sitemap. Mirrors CITY_MIN_LISTINGS in scripts/lib/locations.mjs, so the two
// surfaces can't drift apart.
export const CITY_MIN_LISTINGS = ${CITY_MIN_LISTINGS};

export const CITIES: LocationSummary[] = ${JSON.stringify(cities, null, 2)};

export const STATES: LocationSummary[] = ${JSON.stringify(states, null, 2)};

export const CITIES_BY_TYPE: LocationsByType = ${JSON.stringify(cityByType, null, 2)};

export const STATES_BY_TYPE: LocationsByType = ${JSON.stringify(stateByType, null, 2)};

// Only micromarkets past MICROMARKET_MIN_LISTINGS in scripts/lib/locations.mjs.
export const MICROMARKETS: MicromarketSummary[] = ${JSON.stringify(micromarkets, null, 2)};

// All named micromarkets for filters, including those without a standalone page.
// Counts and city membership use the backend's listing IDs; no tag parsing in the browser.
export const FILTER_MICROMARKETS: MicromarketSummary[] = ${JSON.stringify(filterMarkets, null, 2)};

// Ranked at build time by fresh API listing counts, highest first.
// Ties use the canonical name, then the full location ID.
export const POPULAR_LOCATION_IDS: Record<'states' | 'cities' | 'micromarkets', string[]> = ${JSON.stringify(popular, null, 2)};
`;

  const outDir = path.join('src', 'data');
  const outPath = path.join(outDir, 'locations.generated.ts');
  await fs.mkdir(outDir, { recursive: true });
  await fs.writeFile(outPath, body, 'utf8');
  console.log(
    `[locations] wrote ${outPath} — ${cities.length} cities, ${states.length} states, ${cityByType.PEB.length}+${cityByType.RCC.length} city×type, ${stateByType.PEB.length}+${stateByType.RCC.length} state×type, ${micromarkets.length} micromarkets (from ${warehouses.length} listings)`,
  );
}

main().catch((err) => {
  console.error('[locations] generation failed:', err);
  process.exit(1);
});
