import fs from 'node:fs/promises';
import { API_BASE } from './lib/api.mjs';
import { fetchRead } from '../src/lib/fetchRead.mjs';
import { validateLegalPages } from './lib/legal-content.mjs';

async function main() {
  const response = await fetchRead(`${API_BASE}/legal-pages`, {
    cache: 'no-store', headers: { 'Cache-Control': 'no-cache, no-store' },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`Failed to fetch legal pages: HTTP ${response.status}. Deploy the backend and initialize legal pages first.`);
  const pages = validateLegalPages((await response.json()).data);
  const output = 'src/data/legalPages.generated.ts';
  const body = `// AUTO-GENERATED by scripts/generate-legal-pages.mjs. Published CMS revisions only.\nimport type { LegalContent } from './legalPages';\nexport const legalPages: LegalContent[] = ${JSON.stringify(pages, null, 2)};\n`;
  await fs.writeFile(output, body, 'utf8');
  console.log(`[legal] wrote ${output} — ${pages.length} legal pages`);
}

main().catch(error => { console.error('[legal] generation failed:', error); process.exit(1); });
