// Pulls CMS-authored micromarket page content from the backend and writes the
// TS module the app imports. Same shape as scripts/generate-blogs.mjs — the
// build stays fully static, and the site never talks to the CMS or the database
// at runtime.
//
// Unlike blogs, an empty result is not an error: it means no micromarket has
// editorial content yet, so there are no overview pages. Listing grids are
// always built independently. See fetchMicromarketPages in ./lib/api.mjs.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fetchMicromarketPages, fetchMicromarkets } from './lib/api.mjs';
import { selectNavigationGuide } from './lib/navigation-guide.mjs';

// The API omits unset optional slots rather than sending null, but drop
// undefined keys anyway so the emitted literal stays clean whatever it sends.
const dropUndefined = (obj) =>
  Object.fromEntries(Object.entries(obj).filter(([, v]) => v !== undefined && v !== null));

async function main() {
  const [published, markets] = await Promise.all([fetchMicromarketPages(), fetchMicromarkets()]);
  const pages = published.map(dropUndefined);

  const body = `// AUTO-GENERATED by scripts/generate-micromarkets.mjs — do not edit by hand.
// Regenerated on every \`npm run build\`. Source: backend /micromarket-pages
// (CMS-managed). Types live in ./micromarkets.ts, which re-exports this data.
//
// Only these published records produce /overview pages. Existing micromarket
// listing URLs always render their plain grid independently of this content.
import type { MicromarketContent } from './micromarkets';

export const micromarkets: MicromarketContent[] = ${JSON.stringify(pages, null, 2)};
`;

  const outPath = path.join('src', 'data', 'micromarkets.generated.ts');
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  await fs.writeFile(outPath, body, 'utf8');
  const guide = selectNavigationGuide(pages, markets);
  await fs.writeFile(path.join('src', 'data', 'navigation-guide.generated.ts'),
    `// AUTO-GENERATED by scripts/generate-micromarkets.mjs — do not edit by hand.
// Published CMS content matched to eligible, canonical backend geography.
import type { NavigationGuide } from '@/lib/locationNavigation';

export const navigationGuide: NavigationGuide | null = ${JSON.stringify(guide, null, 2)};
`, 'utf8');
  console.log(
    `[micromarkets] wrote ${outPath} — ${pages.length} editorial pages (${pages.reduce((n, m) => n + (m.faqs?.length ?? 0), 0)} FAQs)`,
  );
}

main().catch((err) => {
  console.error('[micromarkets] generation failed:', err);
  process.exit(1);
});
