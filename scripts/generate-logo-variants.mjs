// Reproducible smaller sources for the existing logo strip; originals stay intact.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const source = 'public/company_logos';
const directory = 'public/optimized-logos';
await fs.mkdir(directory, { recursive: true });
const variants = {};
for (const name of (await fs.readdir(source)).filter(name => name.endsWith('.webp')).sort()) {
  const original = await fs.readFile(path.join(source, name));
  const metadata = await sharp(original).metadata();
  const key = createHash('sha256').update('webp-q75-v1:').update(original).digest('hex').slice(0, 16);
  const entries = [];
  for (const width of [128, 256]) {
    if (width >= metadata.width) continue;
    const bytes = await sharp(original).resize({ width }).webp({ quality: 75, alphaQuality: 100 }).toBuffer();
    if (bytes.length >= original.length) continue;
    const filename = `${key}-${width}.webp`;
    await fs.writeFile(path.join(directory, filename), bytes);
    entries.push(`/optimized-logos/${filename} ${width}w`);
  }
  if (entries.length) variants[`/company_logos/${name}`] = [...entries, `/company_logos/${name} ${metadata.width}w`].join(', ');
}
await fs.writeFile('src/data/logoVariants.generated.ts', `// AUTO-GENERATED by scripts/generate-logo-variants.mjs. Originals are retained.
export const logoVariants: Record<string, string> = ${JSON.stringify(variants, null, 2)};
`);
console.log(`[logos] responsive sources for ${Object.keys(variants).length} logos`);
