// Reproducible responsive WebP sources. Keep the CMS URLs and originals intact.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const directory = 'public/optimized-ad-images';
await fs.mkdir(directory, { recursive: true });
const content = JSON.parse(await fs.readFile('src/data/ad-pages/bangalore.json', 'utf8'));
const sources = new Set(Object.values(content.images).map(image => image.url.split('?')[0]).filter(url => url.startsWith('/') && !url.startsWith('//')));
const variants = {};
for (const source of [...sources].sort()) {
  const original = await fs.readFile(path.join('public', source));
  const metadata = await sharp(original).metadata();
  const key = createHash('sha256').update('webp-q65-effort6-v1:').update(original).digest('hex').slice(0, 16);
  const widths = [...new Set([320, 512, 800, Math.min(1024, metadata.width)].filter(width => width <= metadata.width))].sort((a, b) => a - b);
  const entries = [];
  for (const width of widths) {
    const filename = `${key}-${width}.webp`;
    const output = path.join(directory, filename);
    if (!await fs.access(output).then(() => true, () => false)) {
      const bytes = await sharp(original).resize({ width, withoutEnlargement: true }).webp({ quality: 65, effort: 6 }).toBuffer();
      await fs.writeFile(output, bytes);
    }
    entries.push(`/optimized-ad-images/${filename} ${width}w`);
  }
  variants[source] = entries.join(', ');
}
await fs.writeFile('src/data/adImageVariants.generated.ts', `// AUTO-GENERATED by scripts/generate-ad-image-variants.mjs. Originals are retained.
export const adImageVariants: Record<string, string> = ${JSON.stringify(variants, null, 2)};
`);
console.log(`[ad images] responsive WebP sources for ${Object.keys(variants).length} photos`);
