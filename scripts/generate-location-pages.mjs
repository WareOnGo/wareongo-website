// Pulls CMS-authored city and state page content from the backend and writes the
// TS module the app imports. The twin of scripts/generate-micromarkets.mjs one
// and two levels up — the build stays fully static, and the site never talks to
// the CMS or the database at runtime.
//
// An empty result is not an error: it means nobody has written a city or state
// overview yet. Existing listing pages keep their grids. See
// fetchLocationPages in ./lib/api.mjs.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fetchLocationPages } from './lib/api.mjs';

// The API omits unset optional slots rather than sending null, but drop
// undefined keys anyway so the emitted literal stays clean whatever it sends.
const dropUndefined = (obj) =>
  Object.fromEntries(Object.entries(obj).filter(([, v]) => v !== undefined && v !== null));

async function main() {
  const pages = (await fetchLocationPages()).map(dropUndefined);

  const body = `// AUTO-GENERATED by scripts/generate-location-pages.mjs — do not edit by hand.
// Regenerated on every \`npm run build\`. Source: backend /location-pages
// (CMS-managed). Types live in ./locationPages.ts, which re-exports this data.
//
// An empty array is the normal starting state, and it is not a failure: every
// city/state overview is emitted only after an editor publishes content for it.
import type { LocationPageContent } from './locationPages';

export const locationPages: LocationPageContent[] = ${JSON.stringify(pages, null, 2)};
`;

  const outPath = path.join('src', 'data', 'locationPages.generated.ts');
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  await fs.writeFile(outPath, body, 'utf8');
  const byKind = pages.reduce((acc, p) => ({ ...acc, [p.kind]: (acc[p.kind] ?? 0) + 1 }), {});
  console.log(
    `[locations] wrote ${outPath} — ${pages.length} editorial pages (${byKind.CITY ?? 0} city, ${byKind.STATE ?? 0} state)`,
  );
}

main().catch((err) => {
  console.error('[locations] generation failed:', err);
  process.exit(1);
});
