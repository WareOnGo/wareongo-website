import fs from 'node:fs/promises';
import { API_BASE } from './lib/api.mjs';
import { fetchRead } from '../src/lib/fetchRead.mjs';
import { validateServicePages } from './lib/service-content.mjs';

async function main() {
  const response = await fetchRead(`${API_BASE}/service-pages`, {
    cache: 'no-store', headers: { 'Cache-Control': 'no-cache, no-store' },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`Failed to fetch service pages: HTTP ${response.status}. Deploy the backend service-page endpoint first.`);
  const pages = validateServicePages((await response.json()).data);
  const output = 'src/data/servicePages.generated.ts';
  await fs.writeFile(output, `// AUTO-GENERATED by scripts/generate-service-pages.mjs. Published CMS revisions only.\nimport type { ServicePage } from './servicePages';\nexport const servicePages: ServicePage[] = ${JSON.stringify(pages, null, 2)};\n`, 'utf8');
  console.log(`[services] wrote ${output} — ${pages.length} written, published pages`);
}

main().catch(error => { console.error('[services] generation failed:', error); process.exit(1); });
