import fs from 'node:fs/promises';
import { API_BASE } from './lib/api.mjs';
import { fetchRead } from '../src/lib/fetchRead.mjs';
import { parseAdPages } from './lib/ad-page-content.mjs';
import { pathToFileURL } from 'node:url';

export async function generateAdPages({ read = fetchRead, write = fs.writeFile, base = API_BASE } = {}) {
  const response = await read(`${base}/ad-pages`, {
    cache: 'no-store', headers: { 'Cache-Control': 'no-cache, no-store' }, signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`Ad pages API returned HTTP ${response.status}. Deploy the backend and initialize ad pages first.`);
  const pages = parseAdPages((await response.json()).data);
  await write('src/data/adPages.generated.ts', `// Generated by scripts/generate-ad-pages.mjs. Approved CMS revisions only.\nimport type { AdPageContent } from './adPages';\nexport const adPages: AdPageContent[] = ${JSON.stringify(pages, null, 2)};\n`);
  return pages;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateAdPages().then(pages => console.log(`[ad-pages] wrote ${pages.length} approved page`))
    .catch(error => { console.error('[ad-pages] generation failed:', error); process.exit(1); });
}
