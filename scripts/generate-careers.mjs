import fs from 'node:fs/promises';
import { API_BASE } from './lib/api.mjs';
import { fetchRead } from '../src/lib/fetchRead.mjs';
import { validateCareersContent } from './lib/careers-content.mjs';

async function main() {
  const response = await fetchRead(`${API_BASE}/careers-page`, {
    cache: 'no-store', headers: { 'Cache-Control': 'no-cache, no-store' }, signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}. Deploy the careers backend endpoint and migration before building the website.`);
  const content = validateCareersContent((await response.json()).data);
  const output = 'src/data/careers.generated.ts';
  await fs.writeFile(output, `// AUTO-GENERATED by scripts/generate-careers.mjs. Approved CMS content only.\nimport type { CareersContent } from './careers';\nexport const careersContent: CareersContent | null = ${JSON.stringify(content, null, 2)};\n`, 'utf8');
  console.log(`[careers] wrote ${output} — ${content?.roles.length ?? 0} approved open roles`);
}
main().catch(error => { console.error('[careers] generation failed:', error.message); process.exit(1); });
